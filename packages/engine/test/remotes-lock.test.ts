import {
  type LockUseInput,
  lockIssues,
  type PinContext,
  parseRemotesLock,
  pinFor,
  type RemoteKind,
  type RemoteRefInput,
  type RemotesLock,
  serializeRemotesLock,
} from '@simulci/engine';
import { describe, expect, it } from 'vitest';

const SHA_A = 'a'.repeat(40);
const SHA_B = 'b'.repeat(40);
const SHA_C = 'c'.repeat(40);
const SHA_D = 'd'.repeat(40);
const DIGEST = `sha256-${'A'.repeat(43)}=`;

const DEPLOY = 'octo/ship/.github/workflows/deploy.yml@v1';
const BUILD_AT_A = `octo/ship/.github/workflows/build.yml@${SHA_A}`;

/** A ref as core's `parseRemoteRef` gives it. */
function ref(raw: string, kind: RemoteKind): RemoteRefInput {
  const m = /^([^/@]+)\/([^/@]+)((?:\/[^@]+)?)@(.+)$/.exec(raw)!;
  return { raw, kind, owner: m[1]!, repo: m[2]!, path: m[3]!.replace(/^\//, ''), ref: m[4]! };
}

const entry = (sha: string, kind: RemoteKind, file: string, calls?: string[]) => ({
  sha,
  kind,
  file,
  digest: DIGEST,
  ...(calls ? { calls } : {}),
});

const LOCK: RemotesLock = {
  version: 1,
  remotes: {
    [DEPLOY]: entry(SHA_A, 'workflow', '.github/workflows/deploy.yml', ['actions/cache@v4', BUILD_AT_A]),
    'actions/cache@v4': entry(SHA_B, 'action', 'action.yml'),
    [BUILD_AT_A]: entry(SHA_A, 'workflow', '.github/workflows/build.yml'),
  },
  unreadable: { 'corp/private/.github/workflows/x.yml@v2': 'access' },
};

const lockOf = (text: string): RemotesLock => {
  const read = parseRemotesLock(text);
  if ('error' in read) throw new Error(read.error);
  return read.lock;
};

describe('parseRemotesLock and serializeRemotesLock', () => {
  it('round-trips a lockfile', () => {
    const text = serializeRemotesLock(LOCK);
    expect(lockOf(text)).toEqual(LOCK);
    expect(serializeRemotesLock(lockOf(text))).toBe(text);
  });

  it('writes the canonical form: header, keys sorted, fields in order, calls sorted once each', () => {
    const shuffled: RemotesLock = {
      unreadable: { 'z/z@v1': 'not-found', 'b/b@v1': 'timeout' },
      remotes: {
        'b/b@v1': { digest: DIGEST, file: 'action.yml', kind: 'action', sha: SHA_B },
        'B/b@v0': {
          calls: ['y/y@v1', 'x/x@v1', 'y/y@v1'],
          host: 'github.com',
          sha: SHA_C,
          kind: 'action',
          file: 'action.yaml',
          digest: DIGEST,
        },
        'a/a/.github/workflows/w.yml@v1': entry(SHA_A, 'workflow', '.github/workflows/w.yml', []),
      },
      version: 1,
    };
    expect(serializeRemotesLock(shuffled)).toBe(
      [
        '# Generated by simulci. Run `simulci remotes update` to update it.',
        '# The commit each remote workflow and action this repository uses resolved to, and a digest of the file read there.',
        'version: 1',
        'remotes:',
        '  B/b@v0:',
        `    sha: ${SHA_C}`,
        '    kind: action',
        '    file: action.yaml',
        `    digest: ${DIGEST}`,
        '    host: github.com',
        '    calls:',
        '      - x/x@v1',
        '      - y/y@v1',
        '  a/a/.github/workflows/w.yml@v1:',
        `    sha: ${SHA_A}`,
        '    kind: workflow',
        '    file: .github/workflows/w.yml',
        `    digest: ${DIGEST}`,
        '  b/b@v1:',
        `    sha: ${SHA_B}`,
        '    kind: action',
        '    file: action.yml',
        `    digest: ${DIGEST}`,
        'unreadable:',
        '  b/b@v1: timeout',
        '  z/z@v1: not-found',
        '',
      ].join('\n'),
    );
  });

  it('leaves out an empty unreadable and never folds a long line', () => {
    const long = `octo/ship/${'deep/'.repeat(30)}action@v1`;
    const text = serializeRemotesLock({
      version: 1,
      remotes: { [long]: entry(SHA_A, 'action', 'action.yml') },
      unreadable: {},
    });
    expect(text).not.toContain('unreadable');
    expect(text).toContain(`  ${long}:\n`);
  });

  it('ignores keys it does not know, so a newer version 1 reads', () => {
    const text = `version: 1\nremotes:\n  a/a@v1:\n    sha: ${SHA_A}\n    kind: action\n    file: action.yml\n    digest: ${DIGEST}\n    later: 1\nlater: {}\n`;
    expect(lockOf(text)).toEqual({ version: 1, remotes: { 'a/a@v1': entry(SHA_A, 'action', 'action.yml') } });
  });

  it.each([
    ['not YAML', 'remotes: [', /^not valid YAML: /],
    ['another version', 'version: 2\nremotes: {}\n', /^version: /],
    ['no remotes', 'version: 1\n', /^remotes: /],
    [
      'a key that is not a remote ref',
      `version: 1\nremotes:\n  ./local:\n    sha: ${SHA_A}\n    kind: action\n    file: action.yml\n    digest: ${DIGEST}\n`,
      /^remotes\.\.\/local: a remote ref/,
    ],
    [
      'an upper-case or short SHA',
      `version: 1\nremotes:\n  a/a@v1:\n    sha: ${SHA_A.toUpperCase()}\n    kind: action\n    file: action.yml\n    digest: ${DIGEST}\n`,
      /^remotes\.a\/a@v1\.sha: a commit SHA/,
    ],
    [
      'a digest that is not sha256',
      `version: 1\nremotes:\n  a/a@v1:\n    sha: ${SHA_A}\n    kind: action\n    file: action.yml\n    digest: sha1-x\n`,
      /^remotes\.a\/a@v1\.digest: /,
    ],
    [
      'an unknown failure kind',
      'version: 1\nremotes: {}\nunreadable:\n  a/a@v1: gone\n',
      /^unreadable\.a\/a@v1: /,
    ],
  ])('refuses %s', (_, text, error) => {
    const read = parseRemotesLock(text);
    expect('error' in read && read.error).toMatch(error);
  });
});

describe('pinFor: the precedence table', () => {
  const pin = (raw: string, kind: RemoteKind, ctx: Partial<PinContext> = {}) =>
    pinFor(ref(raw, kind), { mode: 'lock', lock: LOCK, ...ctx });

  it('row 1: a full-SHA ref pins itself in every mode, lower-cased', () => {
    for (const mode of ['off', 'lock', 'fetch'] as const) {
      expect(pin(`octo/x@${SHA_C.toUpperCase()}`, 'action', { mode, actionsLock: SHA_D })).toEqual({
        pinned: 'sha-ref',
        sha: SHA_C,
      });
    }
  });

  it('row 1: a full-SHA ref whose entry records another commit runs the ref, with remote-pin-mismatch', () => {
    const lock: RemotesLock = {
      version: 1,
      remotes: { [`octo/x@${SHA_C}`]: entry(SHA_D, 'action', 'action.yml') },
    };
    expect(pin(`octo/x@${SHA_C}`, 'action', { lock })).toEqual({
      pinned: 'sha-ref',
      sha: SHA_C,
      issue: {
        code: 'remote-pin-mismatch',
        severity: 'warning',
        message: `octo/x@${SHA_C} runs ${SHA_C} (its ref), but .github/simulci/remotes.lock.yml records ${SHA_D}`,
      },
    });
  });

  it('row 2: an action the calling workflow’s actions.lock pins, in every mode, above the lockfile', () => {
    for (const mode of ['off', 'lock', 'fetch'] as const) {
      const got = pin('actions/cache@v4', 'action', { mode, actionsLock: SHA_D.toUpperCase() });
      expect(got.pinned).toBe('actions-lock');
      expect(got.pinned && 'sha' in got && got.sha).toBe(SHA_D);
      // The lockfile records SHA_B: off reads no lockfile, so it reports nothing.
      expect(got.issue?.code).toBe(mode === 'off' ? undefined : 'remote-pin-mismatch');
    }
    expect(pin('actions/cache@v4', 'action', { actionsLock: SHA_B })).toEqual({
      pinned: 'actions-lock',
      sha: SHA_B,
    });
  });

  it('row 2 never pins a reusable workflow, even when actions.lock would match it', () => {
    expect(pin(DEPLOY, 'workflow', { actionsLock: SHA_D })).toEqual({ pinned: 'lockfile', sha: SHA_A });
    expect(pin(DEPLOY, 'workflow', { actionsLock: SHA_D, lock: undefined })).toEqual({});
    expect(pin(DEPLOY, 'workflow', { actionsLock: SHA_D, mode: 'fetch', lock: undefined }).pinned).toBe(
      'resolved',
    );
  });

  it('row 2 does not apply inside a remote unit: the caller’s actions.lock is not its lock', () => {
    expect(pin('actions/cache@v4', 'action', { actionsLock: SHA_D, inRemote: true })).toEqual({
      pinned: 'lockfile',
      sha: SHA_B,
    });
  });

  it('row 3: a ./ inside a remote unit runs at its parent’s commit, in every mode', () => {
    for (const mode of ['off', 'lock', 'fetch'] as const) {
      expect(pin(BUILD_AT_A, 'workflow', { mode, parentSha: SHA_A, inRemote: true })).toEqual({
        pinned: 'parent',
        sha: SHA_A,
      });
    }
    const other = `octo/ship/.github/workflows/build.yml@v1`;
    const lock: RemotesLock = {
      version: 1,
      remotes: { [other]: entry(SHA_B, 'workflow', '.github/workflows/build.yml') },
    };
    expect(pin(other, 'workflow', { lock, parentSha: SHA_A }).issue?.code).toBe('remote-pin-mismatch');
  });

  it('row 4: the lockfile, matched as GitHub matches owner and repository, in lock and fetch modes', () => {
    for (const mode of ['lock', 'fetch'] as const) {
      expect(pin('Actions/Cache@v4', 'action', { mode })).toEqual({ pinned: 'lockfile', sha: SHA_B });
      expect(pin('OCTO/Ship/.github/workflows/deploy.yml@v1', 'workflow', { mode })).toEqual({
        pinned: 'lockfile',
        sha: SHA_A,
      });
    }
    expect(pin('actions/cache@v4', 'action', { mode: 'off' })).toEqual({});
  });

  it('row 4: the exact key first, when two refs differ only in case', () => {
    const lock: RemotesLock = {
      version: 1,
      remotes: {
        'actions/cache@v4': entry(SHA_B, 'action', 'action.yml'),
        'actions/cache@V4': entry(SHA_C, 'action', 'action.yml'),
      },
    };
    expect(pin('actions/cache@V4', 'action', { lock })).toEqual({ pinned: 'lockfile', sha: SHA_C });
    expect(pin('actions/cache@v4', 'action', { lock })).toEqual({ pinned: 'lockfile', sha: SHA_B });
  });

  it('row 5: fetch mode resolves what nothing pins, with remote-unpinned', () => {
    expect(pin('octo/new@v1', 'action', { mode: 'fetch' })).toEqual({
      pinned: 'resolved',
      issue: {
        code: 'remote-unpinned',
        severity: 'info',
        message: 'octo/new@v1 is not in .github/simulci/remotes.lock.yml: resolved live',
      },
    });
    expect(pin('octo/new@v1', 'action', { mode: 'fetch', lock: undefined }).pinned).toBe('resolved');
  });

  it('lock mode reads nothing it cannot pin: remote-not-locked with a lockfile, silence without one', () => {
    expect(pin('octo/new@v1', 'action')).toEqual({
      issue: {
        code: 'remote-not-locked',
        severity: 'warning',
        message: 'octo/new@v1 is not in .github/simulci/remotes.lock.yml',
      },
    });
    expect(pin('corp/private/.github/workflows/x.yml@v2', 'workflow').issue?.message).toBe(
      'corp/private/.github/workflows/x.yml@v2 is not in .github/simulci/remotes.lock.yml (the last update could not read it: access)',
    );
    expect(pin('octo/new@v1', 'action', { lock: undefined })).toEqual({});
    expect(pin('octo/new@v1', 'action', { mode: 'off' })).toEqual({});
  });
});

describe('lockIssues', () => {
  const USES: LockUseInput[] = [
    { ref: DEPLOY, kind: 'workflow', workflow: '.github/workflows/ci.yml' },
    { ref: 'corp/private/.github/workflows/x.yml@v2', kind: 'workflow' },
  ];

  it('finds nothing in a lockfile that covers the closure and only it', () => {
    expect(lockIssues(LOCK, USES)).toEqual([]);
    // A use matched as GitHub matches it, and an actions.lock that agrees.
    expect(
      lockIssues(LOCK, [
        ...USES,
        { ref: 'Actions/cache@v4', kind: 'action', workflow: 'ci.yml', actionsLock: SHA_B },
        {
          ref: 'actions/cache@v4',
          kind: 'action',
          workflow: 'release.yml',
          actionsLock: SHA_B.toUpperCase(),
        },
      ]),
    ).toEqual([]);
  });

  it('reports a ref the closure reaches without an entry, once, and an entry nothing reaches', () => {
    const lock: RemotesLock = {
      version: 1,
      remotes: {
        [DEPLOY]: entry(SHA_A, 'workflow', '.github/workflows/deploy.yml', [
          'actions/cache@v4',
          'octo/gone@v1',
        ]),
        'octo/stale@v1': entry(SHA_B, 'action', 'action.yml'),
      },
      unreadable: { 'octo/stale-too@v1': 'access' },
    };
    expect(
      lockIssues(lock, [
        { ref: DEPLOY, kind: 'workflow' },
        { ref: 'octo/direct@v1', kind: 'action' },
        { ref: 'Octo/direct@v1', kind: 'action' },
      ]),
    ).toEqual([
      {
        code: 'remote-not-locked',
        ref: 'actions/cache@v4',
        message: 'actions/cache@v4 is used, but not locked',
      },
      { code: 'remote-not-locked', ref: 'octo/direct@v1', message: 'octo/direct@v1 is used, but not locked' },
      { code: 'remote-not-locked', ref: 'octo/gone@v1', message: 'octo/gone@v1 is used, but not locked' },
      {
        code: 'remote-lock-unused',
        ref: 'octo/stale-too@v1',
        message: 'octo/stale-too@v1 is locked, but nothing uses it',
      },
      {
        code: 'remote-lock-unused',
        ref: 'octo/stale@v1',
        message: 'octo/stale@v1 is locked, but nothing uses it',
      },
    ]);
  });

  it('reports an action entry an actions.lock pins elsewhere, and two locks that disagree', () => {
    const lock: RemotesLock = {
      version: 1,
      remotes: {
        'actions/cache@v4': entry(SHA_B, 'action', 'action.yml'),
        'actions/setup-node@v4': entry(SHA_B, 'action', 'action.yml'),
        'octo/ship/.github/workflows/deploy.yml@v1': entry(SHA_B, 'workflow', '.github/workflows/deploy.yml'),
      },
    };
    expect(
      lockIssues(lock, [
        { ref: 'actions/cache@v4', kind: 'action', workflow: 'ci.yml', actionsLock: SHA_C },
        { ref: 'actions/setup-node@v4', kind: 'action', workflow: 'ci.yml', actionsLock: SHA_C },
        { ref: 'actions/setup-node@v4', kind: 'action', workflow: 'release.yml', actionsLock: SHA_D },
        { ref: 'actions/setup-node@v4', kind: 'action', workflow: 'docs.yml' },
        // actions.lock never pins a reusable workflow, so a pin a host passes for one is not compared.
        { ref: DEPLOY, kind: 'workflow', workflow: 'ci.yml', actionsLock: SHA_C },
      ]),
    ).toEqual([
      {
        code: 'remote-actions-lock-mismatch',
        ref: 'actions/cache@v4',
        message: `actions.lock pins actions/cache@v4 to ${SHA_C} in ci.yml, but its entry records ${SHA_B}`,
      },
      {
        code: 'remote-actions-lock-conflict',
        ref: 'actions/setup-node@v4',
        message: `actions.lock pins actions/setup-node@v4 to more than one commit: ${SHA_C} in ci.yml, ${SHA_D} in release.yml`,
      },
    ]);
  });

  it('reports a full-SHA key whose entry records another commit', () => {
    const key = `octo/x@${SHA_C.toUpperCase()}`;
    const lock: RemotesLock = {
      version: 1,
      remotes: {
        [key]: entry(SHA_D, 'action', 'action.yml'),
        [`octo/y@${SHA_C}`]: entry(SHA_C, 'action', 'action.yml'),
      },
    };
    expect(
      lockIssues(lock, [
        { ref: key, kind: 'action' },
        { ref: `octo/y@${SHA_C}`, kind: 'action' },
      ]),
    ).toEqual([
      {
        code: 'remote-pin-mismatch',
        ref: key,
        message: `${key} pins ${SHA_C}, but its entry records ${SHA_D}`,
      },
    ]);
  });
});
